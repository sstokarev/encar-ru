/**
 * Numeric label forms: the digits are data and must survive, only the unit
 * is translated. Applied together with TOKEN_MAP (short strings only).
 * Patterns are global so repeated units in one node are all covered.
 */
export const SUFFIX_RULES: readonly { pattern: RegExp; replace: string }[] = [
  // "16/09식" -> "16/09 г.в." (year/month of manufacture in listing rows)
  { pattern: /(\d{2}\/\d{2})\s*식/g, replace: "$1 г.в." },
  // "(19년형)" -> "(19 мод. год)"
  { pattern: /(\d{2})\s*년형/g, replace: "$1 мод. год" },
  // "9인승" -> "9 мест"
  { pattern: /(\d+)\s*인승/g, replace: "$1 мест" },
  // "20개씩 보기" -> "по 20 на странице"
  { pattern: /(\d+)\s*개씩 보기/g, replace: "по $1 на странице" },
  // "38개 옵션 모두보기" -> "все опции (38)"
  { pattern: /(\d+)\s*개 옵션 모두보기/g, replace: "все опции ($1)" },
  // "1건" -> "1 шт."
  { pattern: /(\d+)\s*건(?![가-힣])/g, replace: "$1 шт." },
];

/** Token/suffix replacement is limited to strings no longer than this. */
